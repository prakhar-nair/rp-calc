// Sprite helper - uses Showdown Gen 5 sprites
function getSpriteName(name) {
  return name.toLowerCase()
    .replace(/[^a-z0-9]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}
function getSpriteUrl(name) {
  const n = getSpriteName(name);
  return `https://play.pokemonshowdown.com/sprites/gen5/${n}.png`;
}
function getItemSpriteUrl(item) {
  const n = item.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g,'-');
  return `https://play.pokemonshowdown.com/sprites/itemicons/${n}.png`;
}
